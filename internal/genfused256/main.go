var (
	consts = map[string]float64{}
	inv    bool
	// sp is single precision: complex64 kernels, eight columns per zmm, float32
	// mnemonics and 4-byte constants (set by the complex64 builders).
	sp bool
)

// ps is the packed-single twin of a packed-double mnemonic when sp is set.
func ps(mn string) string {
	if sp {
		return strings.TrimSuffix(mn, "PD") + "PS"
	}
	return mn
}

// ps231 is ps for the FMA forms, whose PD sits before the operand-order digits.
func ps231(mn string) string {
	if sp {
		return strings.Replace(mn, "231PD", "231PS", 1)
	}
	return mn
}

// csDen is cos and sin of 2*pi*num/den, correctly rounded (the 400-bit series
// shared with internal/gendct4); the quarter turns, where the series would
// leave 1e-120 for a zero, are exact.
func csDen(num, den int) (c, s float64) {
	num %= den
	if (4*num)%den == 0 {
		switch 4 * num / den {
		case 0:
			return 1, 0
		case 1:
			return 0, 1
		case 2:
			return -1, 0
		}
		return 0, -1
	}
	return memoCosSin(num, den)
}

// memoCosSin is gentwiddle.CosSin, each angle computed once (the tables of both
// directions and every size read the same angles over and over: a 400-bit series
// each).
func memoCosSin(num, den int) (c, s float64) {
	k := [2]int{num, den}
	if v, ok := cosSinMemo[k]; ok {
		return v[0], v[1]
	}
	c, s = gentwiddle.CosSin(num, den)
	cosSinMemo[k] = [2]float64{c, s}
	return c, s
}

var (
	cosSinMemo   = map[[2]int][2]float64{}
	cosSin32Memo = map[[2]int][2]float32{}
)

// csDen32 is csDen for the complex64 kernels: the 400-bit value rounded once to
// float32 (never float64 and then float32); the quarter turns are exact.
func csDen32(num, den int) (c, s float32) {
	num %= den
	if (4*num)%den == 0 {
		c64, s64 := csDen(num, den)
		return float32(c64), float32(s64)
	}
	k := [2]int{num, den}
	if v, ok := cosSin32Memo[k]; ok {
		return v[0], v[1]
	}
	c, s = gentwiddle.CosSin32(num, den)
	cosSin32Memo[k] = [2]float32{c, s}
	return c, s
}

func cs(m int) (c, s float64) { return csDen(m, 16) }

// twTable is the step-1 twiddle table of one direction: per (k1, group of four
// b) the real parts of w256^(k1*b) each twice, then the imaginary parts each
// twice (forward e^-i, so the sign is flipped for it).
func twTable(inverse bool) []float64 {
	t := make([]float64, 64*16)
	for k1 := 0; k1 < 16; k1++ {
		for g := 0; g < 4; g++ {
			base := (k1*4 + g) * 16
			for l := 0; l < 4; l++ {
				c, s := csDen(k1*(4*g+l), 256)
				if !inverse {
					s = -s
				}
				t[base+2*l], t[base+2*l+1] = c, c
				t[base+8+2*l], t[base+8+2*l+1] = s, s
			}
		}
	}
	return t
}

func twFile() []byte {
	var b strings.Builder
	b.WriteString("// Code generated by internal/genfused256/main.go; DO NOT EDIT.\n\npackage kernels\n\n")
	writeStore(&b, "fused256", "// fused256TwStore is the table of w256^(k1*b), forward then inverse, k1 0..15, b 0..15,\n// in groups of four b: per (k1, group) the real part twice per b, then the\n// imaginary part twice per b, correctly rounded, signed for the direction\n// (forward e^-i).", twTable(false), twTable(true))
	return []byte(b.String())
}

func cname(v float64) string {
	n := fmt.Sprintf("f256_%016x<>", math.Float64bits(v))
	if sp {
		n = fmt.Sprintf("f256s_%08x<>", math.Float32bits(float32(v)))
	}
	consts[n] = v
	return n
}

// ---- the program, as single-assignment instructions ----

type kind int

const (
	kLoad kind = iota
	kStore
	kAdd
	kSub
	kPerm
	kFmaB // mn.BCST const, x, acc->dst (dst takes acc's register)
	kFmaT // mn table, x, acc->dst
	kMulT
	kMulB
	kXorB
	kShuf
	kUnpckL
	kUnpckH
)

type ins struct {
	k   kind
	mn  string
	imm string
	mem string // memory operand, or a constant's name
	src []int
	acc int // accumulator source of a read-modify-write instruction, or -1
	dst int // virtual register written, or -1 for a store
}

var (
	prog []ins
	nv   int
)

func newV() int { nv++; return nv - 1 }

func add1(o ins) int {
	if o.k == kStore {
		o.dst = -1
	} else {
		o.dst = newV()
	}
	prog = append(prog, o)
	return o.dst
}

func ld(base string, off int) int {
	return add1(ins{k: kLoad, mem: fmt.Sprintf("%d(%s)", off, base), acc: -1})
}

func st(v int, base string, off int) {
	add1(ins{k: kStore, mem: fmt.Sprintf("%d(%s)", off, base), src: []int{v}, acc: -1})
}

func addv(a, b int) int { return add1(ins{k: kAdd, src: []int{a, b}, acc: -1}) }
func subv(a, b int) int { return add1(ins{k: kSub, src: []int{a, b}, acc: -1}) }
func perm(a int) int    { return add1(ins{k: kPerm, src: []int{a}, acc: -1}) }
func fmaB(mn string, c float64, x, acc int) int {
	return add1(ins{k: kFmaB, mn: mn, mem: cname(c), src: []int{x}, acc: acc})
}

// radix4 maps four values to the four outputs of a 4-point DFT (forward or
// inverse).
func radix4(a0, a1, a2, a3 int) (o0, o1, o2, o3 int) {
	t0 := addv(a0, a2)
	t1 := subv(a0, a2)
	t2 := addv(a1, a3)
	t3 := subv(a1, a3)
	o0 = addv(t0, t2)
	o2 = subv(t0, t2)
	sw1 := perm(t3)
	sw3 := perm(t3)
	// s1 -/+ i*s3, with sw = swap(s3) = (s3im, s3re):
	//   s1 - i*s3 = (s1re + s3im, s1im - s3re): even +, odd -  (fmsubadd)
	//   s1 + i*s3 = (s1re - s3im, s1im + s3re): even -, odd +  (fmaddsub)
	m1, m3 := ps231("VFMSUBADD231PD"), ps231("VFMADDSUB231PD")
	if inv {
		m1, m3 = m3, m1
	}
	o1 = fmaB(m1, 1, t1, sw1)
	o3 = fmaB(m3, 1, t1, sw3)
	return
}

// cmulConst multiplies r by w_den^m (forward: e^-2 pi i m/den).
func cmulConst(r, m, den int) int {
	m %= den
	if m == 0 {
		return r
	}
	c, s := csDen(m, den)
	if sp {
		c32, s32 := csDen32(m, den)
		c, s = float64(c32), float64(s32)
	}
	if !inv {
		s = -s
	}
	if 2*m == den {
		return add1(ins{k: kXorB, mn: ps("VXORPD"), mem: cname(math.Copysign(0, -1)), src: []int{r}, acc: -1})
	}
	t := perm(r)
	t2 := add1(ins{k: kMulB, mn: ps("VMULPD"), mem: cname(s), src: []int{t}, acc: -1})
	return fmaB(ps231("VFMADDSUB231PD"), c, r, t2)
}

// dft16 takes sixteen values (natural order) and returns the sixteen outputs.
func dft16(in [16]int) (out [16]int) {
	var u [4][4]int // u[k1][j2]
	for j2 := 0; j2 < 4; j2++ {
		u[0][j2], u[1][j2], u[2][j2], u[3][j2] = radix4(in[j2], in[4+j2], in[8+j2], in[12+j2])
	}
	for k1 := 1; k1 < 4; k1++ {
		for j2 := 1; j2 < 4; j2++ {
			u[k1][j2] = cmulConst(u[k1][j2], j2*k1, 16)
		}
	}
	for k1 := 0; k1 < 4; k1++ {
		out[k1], out[k1+4], out[k1+8], out[k1+12] = radix4(u[k1][0], u[k1][1], u[k1][2], u[k1][3])
	}
	return
}

// dft is the DFT of the values in (natural order), a power of two from 1 to 32,
// the same decomposition as dft16: j = B*j1 + j2, k = k1 + A*k2.
func dft(in []int) []int {
	n := len(in)
	switch n {
	case 1:
		return in
	case 2:
		return []int{addv(in[0], in[1]), subv(in[0], in[1])}
	case 4:
		a, b, c, d := radix4(in[0], in[1], in[2], in[3])
		return []int{a, b, c, d}
	}
	if n >= 16 { // radix 4, then n/4-point DFTs
		const A = 4
		B := n / A
		u := make([][]int, A)
		for k := range u {
			u[k] = make([]int, B)
		}
		for j2 := 0; j2 < B; j2++ {
			u[0][j2], u[1][j2], u[2][j2], u[3][j2] = radix4(in[j2], in[B+j2], in[2*B+j2], in[3*B+j2])
		}
		for k1 := 1; k1 < A; k1++ {
			for j2 := 1; j2 < B; j2++ {
				u[k1][j2] = cmulConst(u[k1][j2], j2*k1, n)
			}
		}
		out := make([]int, n)
		for k1 := 0; k1 < A; k1++ {
			o := dft(u[k1])
			for k2 := 0; k2 < B; k2++ {
				out[k1+A*k2] = o[k2]
			}
		}
		return out
	}
	// n == 8: a radix-2 stage, w8 twiddles, radix 4
	const A, B = 2, 4
	var u [A][B]int
	for j2 := 0; j2 < B; j2++ {
		u[0][j2], u[1][j2] = addv(in[j2], in[B+j2]), subv(in[j2], in[B+j2])
	}
	for j2 := 1; j2 < B; j2++ {
		u[1][j2] = cmulConst(u[1][j2], j2, 8)
	}
	out := make([]int, 8)
	for k1 := 0; k1 < A; k1++ {
		o := dft(u[k1][:])
		for k2 := 0; k2 < B; k2++ {
			out[k1+A*k2] = o[k2]
		}
	}
	return out
}

// dftLazy is the n-point DFT (32 or 64), 4 x n/4, with lazy inputs: load(j) is
// called when the first radix-4 stage needs input j (one group at a time, so that
// the n inputs are not all live at once). emit gets each k1's n/4 outputs,
// X[k1+4*k2].
func dftLazy(n int, load func(j int) int, emit func(k1 int, o []int)) {
	const A = 4
	B := n / A
	u := make([][]int, A)
	for k := range u {
		u[k] = make([]int, B)
	}
	for j2 := 0; j2 < B; j2++ {
		var x [A]int
		for j1 := range x {
			x[j1] = load(B*j1 + j2)
		}
		u[0][j2], u[1][j2], u[2][j2], u[3][j2] = radix4(x[0], x[1], x[2], x[3])
	}
	for k1 := 1; k1 < A; k1++ {
		for j2 := 1; j2 < B; j2++ {
			u[k1][j2] = cmulConst(u[k1][j2], j2*k1, n)
		}
	}
	for k1 := 0; k1 < A; k1++ {
		emit(k1, dft(u[k1]))
	}
}

func shuf(imm string, a, b int) int {
	return add1(ins{k: kShuf, imm: imm, src: []int{a, b}, acc: -1})
}

func transpose4(a0, a1, a2, a3 int) (o0, o1, o2, o3 int) {
	t0 := shuf("$0x88", a0, a1)
	t1 := shuf("$0xDD", a0, a1)
	t2 := shuf("$0x88", a2, a3)
	t3 := shuf("$0xDD", a2, a3)
	o0 = shuf("$0x88", t0, t2)
	o1 = shuf("$0x88", t1, t3)
	o2 = shuf("$0xDD", t0, t2)
	o3 = shuf("$0xDD", t1, t3)
	return
}

// build makes one direction's transform (DI dst, SI src, DX table, R8 frame).
func build(inverse bool) {
	inv = inverse
	prog, nv = nil, 0
	for g := 0; g < 4; g++ { // step 1
		var in [16]int
		for a := 0; a < 16; a++ {
			in[a] = ld("SI", (16*a+4*g)*16)
		}
		y := dft16(in)
		for k1 := 1; k1 < 16; k1++ {
			off := (k1*4 + g) * 128
			t := perm(y[k1])
			t2 := add1(ins{k: kMulT, mn: "VMULPD", mem: fmt.Sprintf("%d(DX)", off+64), src: []int{t}, acc: -1})
			y[k1] = add1(ins{k: kFmaT, mn: "VFMADDSUB231PD", mem: fmt.Sprintf("%d(DX)", off), src: []int{y[k1]}, acc: t2})
		}
		for h := 0; h < 4; h++ {
			o0, o1, o2, o3 := transpose4(y[4*h], y[4*h+1], y[4*h+2], y[4*h+3])
			for j, r := range []int{o0, o1, o2, o3} {
				st(r, "R8", (h*16+4*g+j)*64)
			}
		}
	}
	for h := 0; h < 4; h++ { // step 2
		var in [16]int
		for b := 0; b < 16; b++ {
			in[b] = ld("R8", (h*16+b)*64)
		}
		x := dft16(in)
		for k2 := 0; k2 < 16; k2++ {
			st(x[k2], "DI", (16*k2+4*h)*16)
		}
	}
}

// lower emits the program in program order. Registers are allocated lowest
// free first. With rewrite, every second subtract whose minuend dies at it is
// emitted as fma(b, -1, a) into the minuend's register.
func lower(rewrite bool) []string {
	remaining := make([]int, nv)
	for _, o := range prog {
		for _, s := range o.src {
			remaining[s]++
		}
		if o.acc >= 0 {
			remaining[o.acc]++
		}
	}
	phys := make([]int, nv)
	used := [32]bool{}
	alloc := func() int {
		for p := range used {
			if !used[p] {
				used[p] = true
				return p
			}
		}
		panic("genfused256: out of registers")
	}
	z := func(v int) string { return fmt.Sprintf("Z%d", phys[v]) }
	var lines []string
	eligible := 0
	for _, o := range prog {
		// sources whose last use this is
		var dying []int
		seen := map[int]bool{}
		use := func(v int) {
			remaining[v]--
			if remaining[v] == 0 && !seen[v] {
				seen[v] = true
				dying = append(dying, v)
			}
		}
		for _, s := range o.src {
			use(s)
		}
		if o.acc >= 0 {
			use(o.acc)
		}
		// Only a subtract whose minuend dies can be rewritten in place:
		// a - b = fma(b, -1, a) into a's register. No add of this dataflow has a
		// dying source (each radix-4 add shares both operands with the subtract
		// that follows it), and an FMA always reads and overwrites one source, so
		// an add would need a copy first, which measured slower (#162: every add
		// by copy 161.7 ns against 127.5 for these subtracts alone).
		var rw bool
		rwSrc := -1
		if rewrite && o.k == kSub && seen[o.src[0]] {
			eligible++
			if eligible%2 == 1 {
				rw, rwSrc = true, o.src[0]
			}
		}
		// destination register
		switch {
		case o.k == kStore:
		case o.acc >= 0:
			phys[o.dst] = phys[o.acc]
		case rw:
			phys[o.dst] = phys[rwSrc]
		default:
			for _, s := range dying {
				used[phys[s]] = false
			}
			phys[o.dst] = alloc()
			dying = nil
		}
		if o.k != kStore && (o.acc >= 0 || rw) {
			for _, s := range dying {
				if phys[s] != phys[o.dst] {
					used[phys[s]] = false
				}
			}
		}
		if o.k == kStore {
			for _, s := range dying {
				used[phys[s]] = false
			}
		}
		lines = append(lines, render(o, z, rw, rwSrc))
	}
	return lines
}

func render(o ins, z func(int) string, rw bool, rwSrc int) string {
	switch o.k {
	case kLoad:
		return fmt.Sprintf("VMOVUPD %s, %s", o.mem, z(o.dst))
	case kStore:
		return fmt.Sprintf("VMOVUPD %s, %s", z(o.src[0]), o.mem)
	case kAdd, kSub:
		a, b := o.src[0], o.src[1]
		if rw { // a - b with dst = a: b*(-1) + a
			return fmt.Sprintf("%s.BCST %s(SB), %s, %s", ps231("VFMADD231PD"), cname(-1), z(b), z(o.dst))
		}
		mn := ps("VADDPD")
		if o.k == kSub {
			mn = ps("VSUBPD")
		}
		return fmt.Sprintf("%s %s, %s, %s", mn, z(b), z(a), z(o.dst))
	case kPerm:
		if sp {
			return fmt.Sprintf("VPERMILPS $0xB1, %s, %s", z(o.src[0]), z(o.dst))
		}
		return fmt.Sprintf("VPERMILPD $0x55, %s, %s", z(o.src[0]), z(o.dst))
	case kFmaB:
		return fmt.Sprintf("%s.BCST %s(SB), %s, %s", o.mn, o.mem, z(o.src[0]), z(o.dst))
	case kFmaT:
		return fmt.Sprintf("%s %s, %s, %s", o.mn, o.mem, z(o.src[0]), z(o.dst))
	case kMulT:
		return fmt.Sprintf("%s %s, %s, %s", ps("VMULPD"), o.mem, z(o.src[0]), z(o.dst))
	case kMulB:
		return fmt.Sprintf("%s.BCST %s(SB), %s, %s", ps("VMULPD"), o.mem, z(o.src[0]), z(o.dst))
	case kXorB:
		return fmt.Sprintf("%s.BCST %s(SB), %s, %s", ps("VXORPD"), o.mem, z(o.src[0]), z(o.dst))
	case kShuf:
		return fmt.Sprintf("VSHUFF64X2 %s, %s, %s, %s", o.imm, z(o.src[1]), z(o.src[0]), z(o.dst))
	case kUnpckL:
		return fmt.Sprintf("VUNPCKLPD %s, %s, %s", z(o.src[1]), z(o.src[0]), z(o.dst))
	case kUnpckH:
		return fmt.Sprintf("VUNPCKHPD %s, %s, %s", z(o.src[1]), z(o.src[0]), z(o.dst))
	}
	panic("render")
}

// ---- the 1024-point kernel (go-fft/fft#162): 32 x 32, x[32a+b], X[k1+32*k2] ----
//
// Pass 1, per group of four columns b (a loop of eight iterations over one
// generated body): a 32-point DFT across the a axis, the w1024^(k1*b) twiddles
// from a table, a 4x4 transpose of 128-bit lanes into a 16 KB frame. Pass 2, per
// block of four k1: the same DFT across the b axis, contiguous stores. The 32
// values of a 32-point DFT fill the 32 zmm registers, so this lowering spills
// (Belady: the value used furthest ahead) to a scratch area after the frame.

// bigCfg is one A x B fused kernel: n = A*B points, x[B*a+b], X[k1+A*k2]. The
// 1024-point kernel is 32 x 32; the 2048-point one is 64 x 32 or 32 x 64.
type bigCfg struct {
	name string // "fused1024"
	on   string // "Fused1024On"
	A, B int
}

func (c bigCfg) n() int { return c.A * c.B }

// groups is the number of pass-1 iterations (four columns each), blocks the
// number of pass-2 iterations (four k1 each).
func (c bigCfg) groups() int { return c.B / 4 }
func (c bigCfg) blocks() int { return c.A / 4 }

// tableFloats is the length of one direction's pass-1 table: per group and
// k1 = 1..A-1, 16 float64s.
func (c bigCfg) tableFloats() int { return c.groups() * (c.A - 1) * 16 }

func bodyBigA(c bigCfg) {
	prog, nv = nil, 0
	y := make([]int, c.A)
	dftLazy(c.A, func(j int) int { return ld("SI", j*c.B*16) }, func(k1 int, o []int) {
		for k2, v := range o {
			y[k1+4*k2] = v
		}
	})
	for k1 := 1; k1 < c.A; k1++ {
		off := (k1 - 1) * 128
		t := perm(y[k1])
		t2 := add1(ins{k: kMulT, mn: "VMULPD", mem: fmt.Sprintf("%d(DX)", off+64), src: []int{t}, acc: -1})
		y[k1] = add1(ins{k: kFmaT, mn: "VFMADDSUB231PD", mem: fmt.Sprintf("%d(DX)", off), src: []int{y[k1]}, acc: t2})
	}
	for h := 0; h < c.blocks(); h++ {
		o0, o1, o2, o3 := transpose4(y[4*h], y[4*h+1], y[4*h+2], y[4*h+3])
		for j, r := range []int{o0, o1, o2, o3} {
			st(r, "R8", (h*c.B+j)*64)
		}
	}
}

func bodyBigB(c bigCfg) {
	prog, nv = nil, 0
	dftLazy(c.B, func(j int) int { return ld("R8", j*64) }, func(k1 int, o []int) {
		for k2, v := range o {
			st(v, "DI", (k1+4*k2)*c.A*16)
		}
	})
}

// lowerSpill emits prog in program order with 32 zmm registers and spills.
func lowerSpill() (lines []string, slots int) {
	n := nv
	remaining := make([]int, n)
	uses := make([][]int, n)
	for i, o := range prog {
		for _, s := range o.src {
			remaining[s]++
			uses[s] = append(uses[s], i)
		}
		if o.acc >= 0 {
			remaining[o.acc]++
			uses[o.acc] = append(uses[o.acc], i)
		}
	}
	reg := make([]int, n)
	slot := make([]int, n)
	for i := range reg {
		reg[i], slot[i] = -1, -1
	}
	var free [32]bool
	for i := range free {
		free[i] = true
	}
	var freeSlots []int
	cur := 0
	emitl := func(f string, a ...any) { lines = append(lines, fmt.Sprintf(f, a...)) }
	nextUse := func(v int) int {
		for _, u := range uses[v] {
			if u > cur {
				return u
			}
		}
		return 1 << 30
	}
	getReg := func(excl map[int]bool) int {
		for r := range free {
			if free[r] {
				free[r] = false
				return r
			}
		}
		best, bestNext := -1, -1
		for v := 0; v < n; v++ {
			if reg[v] >= 0 && !excl[v] {
				if nu := nextUse(v); nu > bestNext {
					best, bestNext = v, nu
				}
			}
		}
		if best < 0 {
			panic("genfused256: nothing to spill")
		}
		if slot[best] < 0 {
			if len(freeSlots) > 0 {
				slot[best], freeSlots = freeSlots[len(freeSlots)-1], freeSlots[:len(freeSlots)-1]
			} else {
				slot[best] = slots
				slots++
			}
			emitl("VMOVUPD Z%d, %d(R9)", reg[best], slot[best]*64)
		}
		r := reg[best]
		reg[best] = -1
		return r
	}
	z := func(v int) string { return fmt.Sprintf("Z%d", reg[v]) }
	for i, o := range prog {
		cur = i
		need := map[int]bool{}
		for _, s := range o.src {
			need[s] = true
		}
		if o.acc >= 0 {
			need[o.acc] = true
		}
		order := make([]int, 0, len(need))
		for v := range need {
			order = append(order, v)
		}
		sort.Ints(order)
		for _, v := range order {
			if reg[v] < 0 {
				r := getReg(need)
				emitl("VMOVUPD %d(R9), Z%d", slot[v]*64, r)
				reg[v] = r
			}
		}
		var dying []int
		seen := map[int]bool{}
		use := func(v int) {
			remaining[v]--
			if remaining[v] == 0 && !seen[v] {
				seen[v] = true
				dying = append(dying, v)
			}
		}
		for _, s := range o.src {
			use(s)
		}
		if o.acc >= 0 {
			use(o.acc)
		}
		dstReg := -1
		if o.acc >= 0 {
			dstReg = reg[o.acc]
		}
		for _, v := range dying {
			if reg[v] != dstReg {
				free[reg[v]] = true
			}
		}
		if o.k != kStore {
			if dstReg < 0 {
				dstReg = getReg(need)
			}
			reg[o.dst] = dstReg
		}
		emitl("%s", render(o, z, false, -1))
		for _, v := range dying {
			if slot[v] >= 0 {
				freeSlots = append(freeSlots, slot[v])
				slot[v] = -1
			}
			if v != o.dst {
				reg[v] = -1
			}
		}
	}
	return
}

// twTableBig is the pass-1 table of one direction: per group g of four columns
// and k1 = 1..A-1, the real parts of w_n^(k1*b) twice each, then the imaginary
// parts twice each (16 float64s; forward e^-i, so the sign is flipped for it).
func twTableBig(c bigCfg, inverse bool) []float64 {
	t := make([]float64, c.tableFloats())
	for g := 0; g < c.groups(); g++ {
		for k1 := 1; k1 < c.A; k1++ {
			base := (g*(c.A-1) + (k1 - 1)) * 16
			for l := 0; l < 4; l++ {
				cc, s := csDen(k1*(4*g+l), c.n())
				if !inverse {
					s = -s
				}
				t[base+2*l], t[base+2*l+1] = cc, cc
				t[base+8+2*l], t[base+8+2*l+1] = s, s
			}
		}
	}
	return t
}

func twFileBig(c bigCfg) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by internal/genfused256/main.go; DO NOT EDIT.\n\npackage kernels\n\n")
	doc := fmt.Sprintf("// %sTwStore is the pass-1 table of the fused %d-point kernel, forward then\n// inverse: per group of four columns and k1 = 1..%d, 16 float64s, the real\n// parts of w%d^(k1*b) twice each, then the imaginary parts twice each,\n// correctly rounded, signed for the direction (forward e^-i).", c.name, c.n(), c.A-1, c.n())
	writeStore(&b, c.name, doc, twTableBig(c, false), twTableBig(c, true))
	return []byte(b.String())
}

// writeStore writes the table of both directions as one static array, 4 float64s
// (32 bytes) of padding before and after: the linker aligns the array to 32
// bytes at most, and the kernels read the table with 64-byte loads, so init
// (alignedTable in the kernels package) moves the data within the array, in
// place and with no allocation, to the first 64-byte boundary: index 0 or 4.
func writeStore(b *strings.Builder, name, doc string, fwd, inv []float64) {
	fmt.Fprintf(b, "%s\n// The data starts at index 4 (see alignedTable).\nvar %sTwStore = [%d]float64{\n\t0, 0, 0, 0,\n", doc, name, len(fwd)+len(inv)+8)
	for _, t := range [][]float64{fwd, inv} {
		for i, v := range t {
			if i%4 == 0 {
				b.WriteString("\t")
			}
			b.WriteString(strconv.FormatFloat(v, 'g', -1, 64))
			b.WriteString(",")
			if i%4 == 3 {
				b.WriteString("\n")
			} else {
				b.WriteString(" ")
			}
		}
	}
	b.WriteString("\t0, 0, 0, 0,\n}\n")
}

// entryBig emits fused<n> (the gates and a jump, as fused256) and fused<n>body:
// both directions, each a loop over the pass-1 body (one iteration per group of
// four columns) and one over the pass-2 body (one per block of four k1).
func entryBig(c bigCfg) {
	n := c.n()
	fmt.Fprintf(&out, "\n// func %s(dst, src *[%d]complex128, tw *float64, inv bool) (ok bool)\nTEXT ·%s(SB), NOSPLIT, $0-33\n", c.name, n, c.name)
	emit("MOVBLZX ·%s(SB), AX", c.on)
	emit("TESTL AX, AX")
	emit("JZ no")
	emit("MOVBLZX ·UseStockhamAVX512(SB), AX")
	emit("TESTL AX, AX")
	emit("JZ no")
	emit("JMP ·%sbody(SB)", c.name)
	out.WriteString("no:\n")
	emit("MOVB $0, ok+32(FP)")
	emit("RET")
	type dirBody struct{ a, b []string }
	var bodies [2]dirBody
	slots := 0
	for d, inverse := range []bool{false, true} {
		inv = inverse
		bodyBigA(c)
		la, sa := lowerSpill()
		bodyBigB(c)
		lb, sb := lowerSpill()
		bodies[d] = dirBody{la, lb}
		for _, s := range []int{sa, sb} {
			if s > slots {
				slots = s
			}
		}
	}
	data := n * 16 // the frame: the n points, 4x4-transposed
	frame := data + slots*64 + 64
	fmt.Fprintf(&out, "\n// func %sbody(dst, src *[%d]complex128, tw *float64, inv bool) (ok bool)\nTEXT ·%sbody(SB), $%d-33\n", c.name, n, c.name, frame)
	emit("MOVQ dst+0(FP), DI")
	emit("MOVQ src+8(FP), SI")
	emit("MOVQ tw+16(FP), DX")
	emit("MOVQ SP, R11")
	emit("ADDQ $63, R11")
	emit("ANDQ $-64, R11")
	emit("LEAQ %d(R11), R9", data)
	emit("MOVBLZX inv+24(FP), AX")
	emit("TESTL AX, AX")
	emit("JNZ inverse")
	for d, name := range []string{"f", "i"} {
		if d == 1 {
			out.WriteString("inverse:\n")
			emit("ADDQ $%d, DX", c.tableFloats()*8) // the inverse table follows the forward one
		}
		emit("MOVQ R11, R8")
		emit("MOVQ $%d, R10", c.groups())
		emit("PCALIGN $64")
		fmt.Fprintf(&out, "%sloop1:\n", name)
		for _, l := range bodies[d].a {
			emit("%s", l)
		}
		emit("ADDQ $64, SI")
		emit("ADDQ $256, R8")
		emit("ADDQ $%d, DX", (c.A-1)*128)
		emit("DECQ R10")
		emit("JNZ %sloop1", name)
		emit("MOVQ R11, R8")
		emit("MOVQ $%d, R10", c.blocks())
		emit("PCALIGN $64")
		fmt.Fprintf(&out, "%sloop2:\n", name)
		for _, l := range bodies[d].b {
			emit("%s", l)
		}
		emit("ADDQ $%d, R8", c.B*64)
		emit("ADDQ $64, DI")
		emit("DECQ R10")
		emit("JNZ %sloop2", name)
		emit("VZEROUPPER")
		emit("MOVB $1, ok+32(FP)")
		emit("RET")
	}
}

