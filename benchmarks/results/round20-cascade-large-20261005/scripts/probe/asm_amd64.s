#define ADD16 \
	ADDQ BX, AX; ADDQ BX, AX; ADDQ BX, AX; ADDQ BX, AX; \
	ADDQ BX, AX; ADDQ BX, AX; ADDQ BX, AX; ADDQ BX, AX; \
	ADDQ BX, AX; ADDQ BX, AX; ADDQ BX, AX; ADDQ BX, AX; \
