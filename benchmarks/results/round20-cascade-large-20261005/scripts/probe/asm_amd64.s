// func readZ(p *byte, nbytes, reps int) float64
TEXT ·readZ(SB), NOSPLIT, $0-32
	MOVQ p+0(FP), DI
	MOVQ nbytes+8(FP), CX
	MOVQ reps+16(FP), DX
	VPXORQ Z0, Z0, Z0
	VPXORQ Z1, Z1, Z1
	VPXORQ Z2, Z2, Z2
	VPXORQ Z3, Z3, Z3
rep:
	MOVQ DI, SI
	MOVQ CX, BX
loop:
	VADDPD 0(SI), Z0, Z0
	VADDPD 64(SI), Z1, Z1
	VADDPD 128(SI), Z2, Z2
	VADDPD 192(SI), Z3, Z3
	ADDQ $256, SI
	SUBQ $256, BX
	JNZ loop
	DECQ DX
	JNZ rep
	VADDPD Z1, Z0, Z0
	VADDPD Z3, Z2, Z2
	VADDPD Z2, Z0, Z0
	VMOVSD X0, ret+24(FP)
	VZEROUPPER
	RET

