// func chain(n int) int  — n iterations of 16 dependent adds
TEXT ·chain(SB), NOSPLIT, $0-16
	MOVQ n+0(FP), CX
	XORQ AX, AX
	MOVQ $1, BX
loop:
	ADD16
	DECQ CX
	JNZ loop
	MOVQ AX, ret+8(FP)
	RET

// func chainZ(n int) int — same, plus 8 independent 512-bit multiplies
TEXT ·chainZ(SB), NOSPLIT, $0-16
